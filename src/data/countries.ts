/** The 16 SADC member states. Membership is the operator's basis for the resident rate. */
export const SADC_COUNTRIES: ReadonlySet<CountryCode> = new Set([
  'AO', // Angola
  'BW', // Botswana
  'CD', // Democratic Republic of the Congo
  'KM', // Comoros
  'LS', // Lesotho
  'MG', // Madagascar
  'MU', // Mauritius
  'MW', // Malawi
  'MZ', // Mozambique
  'NA', // Namibia
  'SC', // Seychelles
  'SZ', // Eswatini
  'TZ', // Tanzania
  'ZA', // South Africa
  'ZM', // Zambia
  'ZW', // Zimbabwe
]);

const CODES: ReadonlySet<CountryCode> = new Set(COUNTRIES.map(([code]) => code));

export function isCountryCode(code: string): boolean {
  return CODES.has(code);
}

export function countryName(code: string): string {
  return COUNTRIES.find(([c]) => c === code)?.[1] ?? code;
}

/**
 * The rate band for a country. This is the ONLY place the mapping lives: the widget uses it to
 * decide whether to ask for the residency declaration, and the server uses it to price the
 * booking. Anything not in SADC is international, including a code we do not recognise.
 */
export function residencyForCountry(code: string): Residency {
  return SADC_COUNTRIES.has(code) ? 'sadc' : 'international';
}
